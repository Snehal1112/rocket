#!/usr/bin/env node
// Regenerates the design tokens in docs/dsm/index.html from src/globals.css.
// Run it after changing theme tokens so the DSM page cannot drift from the app.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const cssPath = path.join(root, 'src/globals.css');
const dsmPath = path.join(root, 'docs/dsm/index.html');
const START = '/* dsm:tokens:start */';
const END = '/* dsm:tokens:end */';

// Extracts the body of the first block that follows the given pattern.
function block(src, pattern) {
  const m = pattern.exec(src);
  if (!m) throw new Error(`Block not found: ${pattern}`);
  let depth = 0;
  for (let i = m.index + m[0].length - 1; i < src.length; i++) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}' && --depth === 0) return src.slice(m.index + m[0].length, i);
  }
  throw new Error(`Unbalanced block: ${pattern}`);
}

function hslToHex(hue, sat, light) {
  const s = sat / 100;
  const l = light / 100;
  const a = s * Math.min(l, 1 - l);
  const f = (n) => {
    const k = (n + hue / 30) % 12;
    const c = l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1));
    return Math.round(255 * c);
  };
  return [f(0), f(8), f(4)];
}

const hex = ([r, g, b]) =>
  `#${[r, g, b]
    .map((v) => v.toString(16).padStart(2, '0'))
    .join('')
    .toUpperCase()}`;

// Converts one app token value (HSL triple, HSL with alpha, rgba, or plain).
function convert(value) {
  const v = value.replace(/\s+/g, ' ').trim();
  const tri = /^([\d.]+) ([\d.]+)% ([\d.]+)%(?: \/ ([\d.]+))?$/.exec(v);
  if (tri) {
    const rgb = hslToHex(+tri[1], +tri[2], +tri[3]);
    if (tri[4] !== undefined) return `rgba(${rgb.join(', ')}, ${tri[4]})`;
    return hex(rgb);
  }
  return v
    .replace(/rgba\( /g, 'rgba(')
    .replace(/ \)/g, ')')
    .replace(/, ,/g, ',');
}

function parse(body) {
  const tokens = new Map();
  const clean = body.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of clean.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) tokens.set(m[1], convert(m[2]));
  return tokens;
}

const css = fs.readFileSync(cssPath, 'utf8');
const light = parse(block(css, /@layer base \{\s*:root \{/));
const darkOnly = parse(block(css, /\n {2}\.dark \{/));
const dark = new Map([...light, ...darkOnly]);

// DSM short names that point at the real app tokens.
const ALIASES = [
  ['--primary-fg', 'var(--primary-foreground)'],
  ['--secondary-fg', 'var(--secondary-foreground)'],
  ['--muted-fg', 'var(--muted-foreground)'],
  ['--accent-fg', 'var(--accent-foreground)'],
  ['--destructive-fg', 'var(--destructive-foreground)'],
  ['--warning-fg', 'var(--warning-foreground)'],
  ['--sidebar', 'var(--sidebar-bg)'],
  ['--editor', 'var(--editor-bg)'],
  ['--widget', 'var(--editor-widget-bg)'],
  ['--tab-active', 'var(--tab-active-bg)'],
  ['--tab-inactive', 'var(--tab-inactive-bg)'],
  ['--tab-bar', 'var(--tab-inactive-bg)'],
  ['--tab-indicator', 'var(--tab-active-border-top)'],
  ['--list-hover', 'var(--list-hover-bg)'],
  ['--list-active', 'var(--list-active-selection-bg)'],
  ['--focus-border', 'var(--ring)'],
  ['--border-strong', 'var(--input)'],
];

// Shadows are not app tokens (the app uses Tailwind shadow utilities).
const SHADOWS = {
  light: ['0 1px 3px rgba(0,0,0,0.12), 0 1px 2px rgba(0,0,0,0.08)', '0 4px 16px rgba(0,0,0,0.16)'],
  dark: ['0 1px 3px rgba(0,0,0,0.4), 0 1px 2px rgba(0,0,0,0.3)', '0 4px 16px rgba(0,0,0,0.5)'],
};

function emit(theme, tokens) {
  const lines = [`:root[data-theme="${theme}"] {`];
  for (const [name, value] of tokens) lines.push(`  ${name}: ${value};`);
  for (const [name, value] of ALIASES) lines.push(`  ${name}: ${value};`);
  lines.push(`  --radius-lg: var(--radius);`);
  lines.push(`  --radius-md: calc(var(--radius) - 2px);`);
  lines.push(`  --radius-sm: calc(var(--radius) - 4px);`);
  lines.push(`  --shadow: ${SHADOWS[theme][0]};`);
  lines.push(`  --shadow-md: ${SHADOWS[theme][1]};`);
  lines.push('}');
  return lines.join('\n');
}

const generated = [
  START,
  '/* Generated by scripts/sync-dsm-tokens.cjs from src/globals.css. Do not edit by hand. */',
  emit('light', light),
  '',
  emit('dark', dark),
  END,
].join('\n');

let html = fs.readFileSync(dsmPath, 'utf8');
if (html.includes(START)) {
  const re = new RegExp(
    `${START.replace(/[/*]/g, '\\$&')}[\\s\\S]*?${END.replace(/[/*]/g, '\\$&')}`,
  );
  html = html.replace(re, () => generated);
} else {
  // First run: replace the hand-written light and dark token blocks.
  const a = html.indexOf(':root[data-theme="light"] {');
  const dStart = html.indexOf(':root[data-theme="dark"] {');
  const dEnd = html.indexOf('\n}\n', dStart) + 3;
  if (a < 0 || dStart < 0) throw new Error('Token blocks not found in DSM page.');
  html = `${html.slice(0, a)}${generated}\n${html.slice(dEnd)}`;
}
fs.writeFileSync(dsmPath, html);
console.log(`DSM tokens synced: ${light.size} light, ${dark.size} dark.`);
