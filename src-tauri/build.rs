use std::fs;
use std::path::Path;

const COMMANDS_FILE: &str = "app-commands.txt";
const SET_FILE: &str = "permissions/main-window-commands.toml";

/// Reads the command list: one name per line, skipping blank and `#` lines.
fn read_commands() -> Vec<String> {
    fs::read_to_string(COMMANDS_FILE)
        .expect("app-commands.txt is readable")
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_string)
        .collect()
}

/// Writes the permission set that grants every app command to the main window.
fn write_permission_set(commands: &[String]) {
    let permissions: Vec<String> = commands
        .iter()
        .map(|cmd| format!("\"allow-{}\"", cmd.replace('_', "-")))
        .collect();
    let body = format!(
        "# Generated by build.rs from app-commands.txt. Do not edit.\n\
         [[set]]\n\
         identifier = \"main-window-commands\"\n\
         description = \"Allows every app command that the main window uses.\"\n\
         permissions = [\n  {}\n]\n",
        permissions.join(",\n  ")
    );
    fs::create_dir_all(Path::new(SET_FILE).parent().expect("set file has a parent"))
        .expect("permissions dir is created");
    // Skip an identical write: tauri-build watches the folder, so a rewrite dirties every build.
    if fs::read_to_string(SET_FILE).is_ok_and(|old| old == body) {
        return;
    }
    fs::write(SET_FILE, body).expect("permission set is written");
}

fn main() {
    println!("cargo:rerun-if-changed={COMMANDS_FILE}");
    let commands = read_commands();
    write_permission_set(&commands);
    // Leaking is fine in a build script, and `commands` needs a static slice.
    let names: Vec<&'static str> = commands
        .into_iter()
        .map(|cmd| &*Box::leak(cmd.into_boxed_str()))
        .collect();
    let names: &'static [&'static str] = Box::leak(names.into_boxed_slice());
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(names)),
    )
    .expect("tauri-build failed");
}
